import React, { useState, useEffect } from 'react'
import {
  getCheckIns,
  getHabits,
  getAssessmentResults,
  getSafetyPlan,
  getJournalEntries
} from '../utils/api'
import '../styles/ShareReport.css'

const SECTION_OPTIONS = [
  { key: 'overview',     label: 'Wellness Overview',       desc: 'Mood, energy, sleep & stress averages'  },
  { key: 'moodTrend',    label: 'Mood Trend (last 30 days)',desc: 'Daily mood chart'                      },
  { key: 'sleep',        label: 'Sleep Summary',            desc: 'Sleep hours & quality breakdown'       },
  { key: 'assessments',  label: 'Assessment Results',       desc: 'PHQ-9, GAD-7, PCL-5 etc.'             },
  { key: 'goals',        label: 'Goals & Achievements',     desc: 'Active goals and streaks'              },
  { key: 'safetyPlan',   label: 'Crisis Safety Plan',       desc: 'Your personal safety plan steps'      },
  { key: 'checkInNotes', label: 'Recent Check-In Notes',    desc: 'Journal notes from check-ins'         },
]

function avg(arr) {
  const valid = arr.filter(v => v !== undefined && v !== null && !isNaN(v))
  return valid.length ? (valid.reduce((a, b) => a + b, 0) / valid.length).toFixed(1) : '–'
}

function formatDate(ts) {
  return new Date(ts).toLocaleDateString('en', { year: 'numeric', month: 'short', day: 'numeric' })
}

function ShareReport({ userId, user }) {
  const [loading,     setLoading]     = useState(true)
  const [generating,  setGenerating]  = useState(false)
  const [copied,      setCopied]      = useState(false)
  const [sections,    setSections]    = useState(
    Object.fromEntries(SECTION_OPTIONS.map(s => [s.key, true]))
  )
  const [recipientName, setRecipientName] = useState('')
  const [clinicianName, setClinicianName] = useState('')
  const [reportRange,   setReportRange]   = useState('30')
  const [preview,       setPreview]       = useState(false)
  const [reportText,    setReportText]    = useState('')

  // Data
  const [checkIns,     setCheckIns]     = useState([])
  const [habits,       setHabits]       = useState([])
  const [assessments,  setAssessments]  = useState([])
  const [safetyPlan,   setSafetyPlan]   = useState(null)

  useEffect(() => { loadAll() }, [userId])

  const loadAll = async () => {
    try {
      const [ciRes, hRes, aRes, spRes] = await Promise.all([
        getCheckIns(userId),
        getHabits(userId),
        getAssessmentResults(userId),
        getSafetyPlan(userId),
      ])
      setCheckIns(ciRes.data  || [])
      setHabits(hRes.data     || [])
      setAssessments(aRes.data || [])
      setSafetyPlan(spRes.data || null)
    } catch (e) {
      console.error('Error loading report data:', e)
    } finally {
      setLoading(false)
    }
  }

  // Filter check-ins to selected range
  const getFilteredCI = () => {
    const days = parseInt(reportRange)
    const cutoff = new Date()
    cutoff.setDate(cutoff.getDate() - days)
    return checkIns
      .filter(c => new Date(c.timestamp) >= cutoff)
      .sort((a, b) => new Date(a.timestamp) - new Date(b.timestamp))
  }

  // ── Report text builder ─────────────────────────────────────────
  const buildReport = () => {
    const filtered = getFilteredCI()
    const now = new Date().toLocaleDateString('en', { year: 'numeric', month: 'long', day: 'numeric' })
    const rangeLabel = reportRange === '7' ? '7 days' : reportRange === '14' ? '14 days' : reportRange === '30' ? '30 days' : '3 months'

    const line  = '─'.repeat(60)
    const dline = '═'.repeat(60)

    let out = []

    out.push(dline)
    out.push('  MIND SANCTUARY — WELLNESS REPORT')
    out.push(dline)
    out.push(`Report generated: ${now}`)
    out.push(`Reporting period: Last ${rangeLabel}`)
    if (user?.name)      out.push(`Client name:      ${user.name}`)
    if (recipientName)   out.push(`Prepared for:     ${recipientName}`)
    if (clinicianName)   out.push(`Clinician:        ${clinicianName}`)
    out.push('')
    out.push('This report was generated by the Mind Sanctuary mental')
    out.push('health app. It is intended as a supplement to — not a')
    out.push('replacement for — professional clinical assessment.')
    out.push(dline)
    out.push('')

    // ── Overview ──
    if (sections.overview && filtered.length > 0) {
      out.push(line)
      out.push('WELLNESS OVERVIEW')
      out.push(line)
      out.push(`Check-ins recorded:  ${filtered.length} in the last ${rangeLabel}`)
      out.push(`Average mood:        ${avg(filtered.map(c => c.mood))}/10`)
      out.push(`Average energy:      ${avg(filtered.map(c => c.energy))}/10`)
      out.push(`Average sleep:       ${avg(filtered.map(c => c.sleep?.hours))}h per night`)
      out.push(`Average stress:      ${avg(filtered.map(c => c.stress?.level))}/10`)

      const moodVals = filtered.map(c => c.mood).filter(Boolean)
      if (moodVals.length >= 4) {
        const mid = Math.floor(moodVals.length / 2)
        const first  = moodVals.slice(0, mid).reduce((a,b) => a+b, 0) / mid
        const second = moodVals.slice(mid).reduce((a,b) => a+b, 0) / (moodVals.length - mid)
        const diff = second - first
        const trend = diff > 0.5 ? '↑ Improving' : diff < -0.5 ? '↓ Declining' : '→ Stable'
        out.push(`Mood trend:          ${trend}`)
      }
      out.push('')
    }

    // ── Mood Trend ──
    if (sections.moodTrend && filtered.length > 0) {
      out.push(line)
      out.push('MOOD TREND')
      out.push(line)
      const last14 = filtered.slice(-14)
      last14.forEach(c => {
        const d    = new Date(c.timestamp).toLocaleDateString('en', { weekday: 'short', month: 'short', day: 'numeric' })
        const mood = c.mood || 0
        const bar  = '█'.repeat(mood) + '░'.repeat(10 - mood)
        const label = mood >= 8 ? 'Great' : mood >= 6 ? 'Good' : mood >= 4 ? 'Fair' : 'Low'
        out.push(`  ${d.padEnd(14)} ${bar}  ${mood}/10  (${label})`)
      })
      out.push('')
    }

    // ── Sleep ──
    if (sections.sleep && filtered.length > 0) {
      out.push(line)
      out.push('SLEEP SUMMARY')
      out.push(line)
      const sleepHours = filtered.map(c => c.sleep?.hours).filter(Boolean)
      if (sleepHours.length) {
        out.push(`Average:    ${avg(sleepHours)}h per night`)
        out.push(`Best night: ${Math.max(...sleepHours)}h`)
        out.push(`Worst night:${Math.min(...sleepHours)}h`)
        out.push(`Nights ≥7h: ${sleepHours.filter(h => h >= 7).length} of ${sleepHours.length} (${Math.round(sleepHours.filter(h=>h>=7).length/sleepHours.length*100)}%)`)

        const qualCounts = {}
        filtered.forEach(c => {
          const q = c.sleep?.quality || 'unknown'
          qualCounts[q] = (qualCounts[q] || 0) + 1
        })
        out.push('Quality breakdown:')
        Object.entries(qualCounts).sort((a,b)=>b[1]-a[1]).forEach(([q,n]) => {
          out.push(`  ${q.padEnd(10)} ${n} nights (${Math.round(n/filtered.length*100)}%)`)
        })
      }
      out.push('')
    }

    // ── Assessments ──
    if (sections.assessments && assessments.length > 0) {
      out.push(line)
      out.push('ASSESSMENT RESULTS')
      out.push(line)
      // Show latest result per assessment type
      const latestByType = {}
      assessments.forEach(a => {
        if (!latestByType[a.assessmentId] || new Date(a.timestamp) > new Date(latestByType[a.assessmentId].timestamp)) {
          latestByType[a.assessmentId] = a
        }
      })
      Object.values(latestByType).forEach(a => {
        out.push(`${a.assessmentName}`)
        out.push(`  Score:    ${a.totalScore}/${a.maxScore} (${a.percentage}%)`)
        out.push(`  Severity: ${a.severity.toUpperCase()}`)
        out.push(`  Date:     ${formatDate(a.timestamp)}`)
        out.push('')
      })
    }

    // ── Goals ──
    if (sections.goals && habits.length > 0) {
      out.push(line)
      out.push('GOALS & ACHIEVEMENTS')
      out.push(line)
      habits.forEach(h => {
        const streak = h.streak || 0
        const streakLabel = streak >= 7 ? '🔥 Strong streak' : streak >= 3 ? 'Building' : streak > 0 ? 'Started' : 'New'
        out.push(`  • ${h.name}`)
        out.push(`    Category: ${h.category} | Frequency: ${h.frequency} | Streak: ${streak} days (${streakLabel})`)
        if (h.goal) out.push(`    Target: ${h.goal}`)
      })
      out.push('')
    }

    // ── Safety Plan ──
    if (sections.safetyPlan && safetyPlan) {
      out.push(line)
      out.push('CRISIS SAFETY PLAN')
      out.push(line)
      out.push('(Shared with consent for clinical review)')
      out.push('')
      if (safetyPlan.step1_warningSigns?.length) {
        out.push('Warning Signs:')
        safetyPlan.step1_warningSigns.forEach(s => out.push(`  • ${s}`))
        out.push('')
      }
      if (safetyPlan.step2_internalCoping?.length) {
        out.push('Internal Coping Strategies:')
        safetyPlan.step2_internalCoping.forEach(s => out.push(`  • ${s}`))
        out.push('')
      }
      if (safetyPlan.step3_contacts?.length) {
        out.push('Support Contacts:')
        safetyPlan.step3_contacts.forEach(c => out.push(`  • ${c.name}${c.phone ? ' — ' + c.phone : ''}`))
        out.push('')
      }
      if (safetyPlan.step6_reasonsToLive?.length) {
        out.push('Reasons for Living:')
        safetyPlan.step6_reasonsToLive.forEach(s => out.push(`  • ${s}`))
        out.push('')
      }
    }

    // ── Check-in notes ──
    if (sections.checkInNotes) {
      const withNotes = filtered.filter(c => c.journalNote?.trim() || c.couldHelp?.trim())
      if (withNotes.length > 0) {
        out.push(line)
        out.push('RECENT CHECK-IN NOTES')
        out.push(line)
        withNotes.slice(-10).forEach(c => {
          out.push(`${formatDate(c.timestamp)} — Mood ${c.mood}/10`)
          if (c.journalNote) out.push(`  Note: ${c.journalNote}`)
          if (c.couldHelp)   out.push(`  What could help: ${c.couldHelp}`)
          out.push('')
        })
      }
    }

    out.push(dline)
    out.push('END OF REPORT — Mind Sanctuary')
    out.push('This report contains personal health information.')
    out.push('Please handle with appropriate confidentiality.')
    out.push(dline)

    return out.join('\n')
  }

  const handleGenerate = () => {
    setGenerating(true)
    setTimeout(() => {
      const text = buildReport()
      setReportText(text)
      setPreview(true)
      setGenerating(false)
    }, 400)
  }

  const handleCopy = async () => {
    try {
      await navigator.clipboard.writeText(reportText)
      setCopied(true)
      setTimeout(() => setCopied(false), 2500)
    } catch {
      // fallback
      const ta = document.createElement('textarea')
      ta.value = reportText
      document.body.appendChild(ta)
      ta.select()
      document.execCommand('copy')
      document.body.removeChild(ta)
      setCopied(true)
      setTimeout(() => setCopied(false), 2500)
    }
  }

  const handleDownload = () => {
    const name = user?.name?.replace(/\s+/g, '_') || 'client'
    const date = new Date().toISOString().split('T')[0]
    const filename = `MindSanctuary_Report_${name}_${date}.txt`
    const blob = new Blob([reportText], { type: 'text/plain' })
    const url  = URL.createObjectURL(blob)
    const a    = document.createElement('a')
    a.href     = url
    a.download = filename
    a.click()
    URL.revokeObjectURL(url)
  }

  const handleEmail = () => {
    const subject = encodeURIComponent(`Mind Sanctuary Wellness Report — ${user?.name || 'Client'}`)
    const body = encodeURIComponent(
      `Hi${clinicianName ? ' ' + clinicianName : ''},\n\nPlease find attached my Mind Sanctuary wellness report.\n\nGenerated: ${new Date().toLocaleDateString()}\nClient: ${user?.name || 'Client'}\n\nThis report was generated by the Mind Sanctuary mental health app.\n\nPlease download the report file and attach it to this email before sending.\n\nKind regards,\n${user?.name || ''}`
    )
    const a = document.createElement('a')
    a.href = `mailto:?subject=${subject}&body=${body}`
    a.click()
  }

  const filtered = getFilteredCI()

  if (loading) {
    return <div className="report-container"><div className="report-loading">Loading your data...</div></div>
  }

  return (
    <div className="report-container">

      {/* Header */}
      <div className="report-header">
        <div>
          <h1>📋 Share with Clinician</h1>
          <p className="report-subtitle">Generate a wellness report to share with your counsellor, psychologist or mental health nurse</p>
        </div>
      </div>

      {!preview ? (
        <div className="report-builder">

          {/* Data snapshot */}
          <div className="report-snapshot">
            <div className="snapshot-item">
              <span className="snapshot-val">{checkIns.length}</span>
              <span className="snapshot-label">Check-ins</span>
            </div>
            <div className="snapshot-item">
              <span className="snapshot-val">{assessments.length}</span>
              <span className="snapshot-label">Assessments</span>
            </div>
            <div className="snapshot-item">
              <span className="snapshot-val">{habits.length}</span>
              <span className="snapshot-label">Goals</span>
            </div>
            <div className="snapshot-item">
              <span className="snapshot-val" style={{ color: safetyPlan ? '#10b981' : '#ef4444' }}>
                {safetyPlan ? 'Yes' : 'No'}
              </span>
              <span className="snapshot-label">Safety Plan</span>
            </div>
          </div>

          {/* Settings */}
          <div className="report-card">
            <h2>⚙️ Report Settings</h2>

            <div className="report-field">
              <label>Time range</label>
              <div className="range-row">
                {[['7','7 days'],['14','14 days'],['30','30 days'],['90','3 months']].map(([v,l]) => (
                  <button
                    key={v}
                    className={`range-btn ${reportRange === v ? 'active' : ''}`}
                    onClick={() => setReportRange(v)}
                  >
                    {l}
                  </button>
                ))}
              </div>
              <p className="field-note">{filtered.length} check-ins in this range</p>
            </div>

            <div className="report-field">
              <label>Clinician name <span className="optional">(optional)</span></label>
              <input
                className="report-input"
                placeholder="e.g. Dr. Sarah Jones"
                value={clinicianName}
                onChange={e => setClinicianName(e.target.value)}
              />
            </div>

            <div className="report-field">
              <label>Prepared for <span className="optional">(optional)</span></label>
              <input
                className="report-input"
                placeholder="e.g. Psychology clinic, Mental health team"
                value={recipientName}
                onChange={e => setRecipientName(e.target.value)}
              />
            </div>
          </div>

          {/* Section selector */}
          <div className="report-card">
            <h2>📌 Sections to Include</h2>
            <p className="card-note">Choose what to share. Untick anything you'd prefer to keep private.</p>
            <div className="sections-list">
              {SECTION_OPTIONS.map(s => {
                const hasData =
                  s.key === 'assessments'  ? assessments.length > 0 :
                  s.key === 'goals'        ? habits.length > 0 :
                  s.key === 'safetyPlan'   ? !!safetyPlan :
                  filtered.length > 0
                return (
                  <div
                    key={s.key}
                    className={`section-item ${!hasData ? 'no-data' : ''}`}
                    onClick={() => hasData && setSections(p => ({ ...p, [s.key]: !p[s.key] }))}
                  >
                    <input
                      type="checkbox"
                      checked={sections[s.key]}
                      onChange={e => setSections(p => ({ ...p, [s.key]: e.target.checked }))}
                      disabled={!hasData}
                      onClick={e => e.stopPropagation()}
                    />
                    <div className="section-info">
                      <span className="section-label">{s.label}</span>
                      <span className="section-desc">
                        {!hasData ? 'No data available' : s.desc}
                      </span>
                    </div>
                  </div>
                )
              })}
            </div>
          </div>

          {/* Privacy notice */}
          <div className="report-privacy">
            <strong>🔒 Your privacy:</strong> This report is generated entirely on your device. Nothing is automatically sent anywhere — you choose exactly what to share and with whom.
          </div>

          <button
            className="report-generate-btn"
            onClick={handleGenerate}
            disabled={generating || filtered.length === 0}
          >
            {generating ? 'Generating...' : '📋 Generate Report'}
          </button>

          {filtered.length === 0 && (
            <p className="report-no-data">No check-in data in the selected time range. Try a longer range or complete a check-in first.</p>
          )}
        </div>
      ) : (
        /* ── Preview & Share ── */
        <div className="report-preview-wrap">
          <div className="report-preview-actions">
            <button className="report-back-btn" onClick={() => setPreview(false)}>← Edit settings</button>
            <div className="preview-share-btns">
              <button className={`share-btn copy-btn ${copied ? 'copied' : ''}`} onClick={handleCopy}>
                {copied ? '✓ Copied!' : '📋 Copy text'}
              </button>
              <button className="share-btn download-btn" onClick={handleDownload}>
                ⬇️ Download .txt
              </button>
              <button className="share-btn email-btn" onClick={handleEmail}>
                ✉️ Open in email
              </button>
            </div>
          </div>

          <div className="report-instructions">
            <strong>How to share:</strong>
            <span>Download the file first, then click "Open in email" to open your mail app — attach the downloaded file before sending.</span>
          </div>

          <pre className="report-text-preview">{reportText}</pre>

          <div className="report-preview-actions bottom">
            <div className="preview-share-btns">
              <button className={`share-btn copy-btn ${copied ? 'copied' : ''}`} onClick={handleCopy}>
                {copied ? '✓ Copied!' : '📋 Copy text'}
              </button>
              <button className="share-btn download-btn" onClick={handleDownload}>
                ⬇️ Download .txt
              </button>
              <button className="share-btn email-btn" onClick={handleEmail}>
                ✉️ Open in email
              </button>
            </div>
          </div>
        </div>
      )}
    </div>
  )
}

export default ShareReport
